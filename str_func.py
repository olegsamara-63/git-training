def to_uppercase(s: str) -> str:
    """Изменение: типа внесено изменение добавилась строчка в Коде-комментарий ввиде текста Возращает строку в верхнем регистре"""
    return s.upper()


def capitalize_words(s: str) -> str:
    """Возвращает строку с заглавными первыми буквами каждого слова."""
    return s.title()
